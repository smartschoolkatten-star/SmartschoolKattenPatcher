#!/usr/bin/env python3
"""Build the injected runtime and icon XML with locally installed Android tools."""
import argparse
import base64
import json
import os
from pathlib import Path
import shutil
import subprocess
import zipfile

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument("--sdk", type=Path, default=Path.home() / "Android/Sdk")
parser.add_argument("--java-home", type=Path, default=Path(os.environ["JAVA_HOME"]) if "JAVA_HOME" in os.environ else None)
args = parser.parse_args()
if args.java_home is None:
    parser.error("Geef --java-home of stel JAVA_HOME in op de Gradle JDK van Android Studio")
build_tools = sorted((args.sdk / "build-tools").iterdir(), key=lambda p: tuple(int(x) for x in p.name.split('.') if x.isdigit()))[-1]
android = args.sdk / "platforms/android-37.0/android.jar"
if not android.exists():
    parser.error("Android SDK platform 37.0 ontbreekt")
work = root / "build/patch-payload"
if work.exists():
    shutil.rmtree(work)
classes = work / "classes"
classes.mkdir(parents=True)
assets = root / "app/src/main/assets/patch"
assets.mkdir(parents=True, exist_ok=True)
java = args.java_home / "bin/java"

def run(*command):
    subprocess.run([str(x) for x in command], check=True)

run(args.java_home / "bin/javac", "--release", "11", "-classpath", android,
    "-d", classes, *sorted((root / "patch-runtime/src").rglob("*.java")))
run(args.java_home / "bin/jar", "cf", work / "runtime.jar", "-C", classes, ".")
run(java, "-cp", build_tools / "lib/d8.jar", "com.android.tools.r8.D8", "--min-api", "32",
    "--lib", android, "--output", classes, work / "runtime.jar")
shutil.copyfile(classes / "classes.dex", assets / "runtime.dex")
# Keep the injected DEX with the Java engine, avoiding stale AssetManager overlays.
encoded = base64.b64encode((classes / "classes.dex").read_bytes()).decode("ascii")
chunks = [encoded[i:i + 12000] for i in range(0, len(encoded), 12000)]
java_payload = root / "app/src/main/java/be/smartschoolkatten/patcher/engine/RuntimePayload.java"
source = ("package be.smartschoolkatten.patcher.engine;\n\n"
          "/** Generated by tools/build-payload.py; compiled together with the patch engine. */\n"
          "public final class RuntimePayload {\n"
          "    private RuntimePayload() {}\n"
          "    private static final String[] PARTS = {\n"
          + ",\n".join('        "' + chunk + '"' for chunk in chunks)
          + "\n    };\n"
          "    public static byte[] data() { return java.util.Base64.getDecoder().decode(String.join(\"\", PARTS)); }\n"
          "}\n")
if not java_payload.exists() or java_payload.read_text() != source:
    java_payload.write_text(source)

shutil.copytree(root / "tools/icon-res", work / "res")
shutil.copyfile(root / "assets/branding/smartschool-katten-icon-source.jpg", work / "res/drawable/ic_launcher_foreground.jpg")
run(build_tools / "aapt2", "compile", "--dir", work / "res", "-o", work / "resources.zip")
run(build_tools / "aapt2", "link", "-o", work / "icons.apk", "-I", android,
    "--manifest", root / "tools/icon-manifest.xml", "--stable-ids", root / "tools/icon-ids.txt", work / "resources.zip")
with zipfile.ZipFile(work / "icons.apk") as package:
    (assets / "icon-background.xml").write_bytes(package.read("res/drawable/ic_launcher_background.xml"))
    (assets / "icon-adaptive.xml").write_bytes(package.read("res/mipmap-anydpi-v26/ic_launcher.xml"))
shutil.copyfile(root / "assets/branding/smartschool-katten-icon-source.jpg", assets / "icon.jpg")
branding_classes = work / "branding-classes"
branding_classes.mkdir()
run(args.java_home / "bin/javac", "--release", "11", "-d", branding_classes,
    root / "tools/BuildBranding.java")
run(java, "-Djava.awt.headless=true", "-cp", branding_classes, "BuildBranding",
    root / "assets/branding/smartschool-katten-icon-source.jpg", assets)
links = json.loads((root / "docs/extension-assets.json").read_text())["catUrls"]
(assets / "cat-urls.txt").write_text("\n".join(links) + "\n")
print("Patchpayload en launcherresources gebouwd")
